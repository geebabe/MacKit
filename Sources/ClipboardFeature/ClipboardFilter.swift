// ClipboardFeature/ClipboardFilter.swift
// Privacy and exclusion filters for incoming clipboard changes.
// Detects password managers, transient items, and oversized payloads.

import Foundation
import AppKit
import Diagnostics

/// Known pasteboard types marking sensitive or transient clipboard data.
public enum SensitivePasteboardType {
    public static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    public static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    public static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    public static let onePassword = NSPasteboard.PasteboardType("com.agilebits.onepassword")
    public static let confidential = NSPasteboard.PasteboardType("de.dstoecker.x-clipboard-content-type-confidential")

    public static let allKnown: [NSPasteboard.PasteboardType] = [
        concealed, transient, autoGenerated, onePassword, confidential
    ]
}

/// Validates whether a clipboard item should be captured or rejected.
public struct ClipboardFilter: Sendable {

    /// Maximum accepted payload limits in bytes (from PRD spec).
    public static let maxTextSizeBytes: Int = 10 * 1024 * 1024    // 10 MiB
    public static let maxImageSizeBytes: Int = 25 * 1024 * 1024   // 25 MiB

    public init() {}

    /// Check if the pasteboard item contains any concealed or transient markers.
    public func isConcealedOrTransient(types: [NSPasteboard.PasteboardType]) -> Bool {
        for sensitive in SensitivePasteboardType.allKnown {
            if types.contains(sensitive) {
                return true
            }
        }
        return false
    }

    /// Check if the originating application is excluded.
    public func isAppExcluded(bundleID: String?, excludedBundleIDs: Set<String>) -> Bool {
        guard let bundleID else { return false }
        return excludedBundleIDs.contains(bundleID)
    }

    /// Validate text payload size.
    public func validateTextSize(byteCount: Int) -> Result<Void, ClipboardRejectionReason> {
        if byteCount > Self.maxTextSizeBytes {
            return .failure(.payloadTooLarge(kind: "Text", sizeBytes: byteCount, limitBytes: Self.maxTextSizeBytes))
        }
        return .success(())
    }

    /// Validate image payload size.
    public func validateImageSize(byteCount: Int) -> Result<Void, ClipboardRejectionReason> {
        if byteCount > Self.maxImageSizeBytes {
            return .failure(.payloadTooLarge(kind: "Image", sizeBytes: byteCount, limitBytes: Self.maxImageSizeBytes))
        }
        return .success(())
    }
}
